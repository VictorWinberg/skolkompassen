function normalizeName(n: string) {
  return n
    .trim()
    .toLowerCase()
    .replace(/[\s.,/-]+/g, "_");
}

export function getLocation(s: School | string) {
  const name = typeof s === "string" ? s : s.name;
  return locations[normalizeName(name)];
}
